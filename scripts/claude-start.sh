#!/usr/bin/env bash
# Launch Claude Code seeded with a primer about this Ansible homelab repo, so a
# fresh session starts knowing the hard rules instead of rediscovering them (or
# worse, violating them — running raw ansible-playbook, installing host tools,
# committing to git). Any extra arguments are passed straight through as the
# session's task.
#
#   ./scripts/claude-start.sh                     # start with the primer
#   ./scripts/claude-start.sh 'fix the gpu phase' # ...plus a task for the session
#   CLAUDE_ARGS=--model=opus ./scripts/claude-start.sh
#   task claude:start                             # the same, via the task runner
#
# NOTE: this primer is deliberately self-contained. CLAUDE.md in this repo is a
# committed XSym blob (an SMB-style symlink stored as literal text) rather than a
# real symlink to agent.md, so nothing resolves it and agent.md does NOT reach
# Claude automatically. Until that's fixed, this script is the only thing that
# puts these conventions in front of a session.
set -euo pipefail

cd "$(dirname "$0")/.."

PROMPT="$(cat <<'EOF'
This is an Ansible-based homelab provisioning repo. Essential working context:

PUBLIC REPO — this is published. Only things safe to make public belong in the
tree. Never commit secrets: credentials live in group_vars/all/vault.yml
(Ansible Vault, ciphertext is safe to commit) and the vault password itself
lives OUTSIDE the repo at ~/.config/homelab/vault-pass. public_keys/ holds
public keys only.

TOOLING — everything runs in containers; the host needs only Docker and
go-task. No Python, Ansible, ansible-lint, or galaxy collections on the host.
The runner image is Dockerfile + docker-compose.yml.

ALL TASKS GO THROUGH THE TASKFILE. Do not suggest or run raw ansible-playbook,
ansible, ansible-lint, ansible-vault, docker compose, or ansible-galaxy. If a
workflow has no Task, add one to Taskfile.yml rather than running it ad-hoc.
`task --list` is the index.

LAYOUT
- setup-debian.yml   — bootstrap for fresh VMs in [init]; imports every baseline
                       phase.
- setup-<role>.yml   — per-role (docker, gpu, wings, jellyfin). Each re-runs the
                       full baseline then layers its phase on top, idempotently.
- playbooks/debian-<phase>.yml — one playbook per phase, each independently
                       runnable via its own deploy:* task. Every phase uses
                       hosts: "{{ target_hosts | default(...) }}" so it's
                       reusable across groups.
- group_vars/all/main.yml — defaults for every group. group_vars/<group>.yml
                       overrides those; host_vars/<host>.yml overrides those.
- inventory          — [init] for fresh DHCP boxes, then role groups by static
                       IP/FQDN. Hosts move out of [init] after bootstrap.
- scripts/server-bootstrap.sh — one-time root-side prep run on the target before
                       Ansible takes over.

CREDENTIALS — both are compose secrets, so they exist inside the runner only.
- SSH: ~/.ssh/id_ed25519 (override: ANSIBLE_SSH_KEY), mounted to
  /root/.ssh/id_ansible, which ansible.cfg points at. debian-basic.yml
  authorizes EVERY public_keys/*.pub, so rotating a key is "drop the .pub in,
  re-run the phase".
- Vault: ~/.config/homelab/vault-pass, generated by `task vault:init` (a dep of
  build:container, so it self-heals). ansible.cfg reads it from
  /run/secrets/vault_pass. group_vars/all/vault.yml holds
  ansible_become_password. Edit with `task vault:edit`, read with
  `task vault:view`. Sudo is password-gated on purpose — NOT a NOPASSWD
  sudoers rule — so a stolen SSH key alone doesn't get root. An empty vault
  password file makes ansible fail on EVERY run, even with nothing encrypted.

TESTING — run these before considering a playbook change done.
- `task syntax`            — syntax-check every top-level playbook.
- `task molecule:test:all` — both Molecule scenarios: `default` (container-safe
                             baseline phases) and `jellyfin` (the Jellyfin role
                             phase, which parses the rendered compose file so a
                             template typo fails in CI rather than on a host).
                             Single scenario: `task molecule:test SCENARIO=...`.
- `task check`             — --check --diff dry run against real inventory.
- `task ping`              — verify SSH + become reach every host. Run this
                             first when debugging; if it fails, nothing else
                             will work.
- `task lint` is RED at HEAD (~62 pre-existing ansible-lint style findings:
  name[play], yaml[truthy], name[casing]). Don't mistake that for a regression
  you caused; check whether your lines are among the findings.

GOTCHAS that cost real time
- Ansible templates module args, so Go templates collide with Jinja: passing
  `docker ... --format '{{.Names}}'` through `task adhoc` fails with
  "Syntax error in template: unexpected '.'". Use plain output and awk/grep.
- /sbin and /usr/sbin are not on PATH for the remote user in non-login shells.
  swapon, resize2fs, parted, sfdisk etc. appear "missing" — use absolute paths.
- Hosts can carry stacks Ansible doesn't manage (deployed via Portainer), so
  disk/RAM assumptions in host_vars may understate real usage. Check the host
  before trusting them.

GIT — managed by the user. Never commit, stage, or otherwise modify the index or
history. Report load-bearing git-state findings and give the command to run;
don't run it. Work happens on branch 0.1.x.

Deeper detail lives in agent.md and README.md — read them when you need it.
Keep this context and these conventions in mind throughout the session.
EOF
)"

if [ "$#" -gt 0 ]; then
  PROMPT="${PROMPT}

The task for this session: $*"
fi

# shellcheck disable=SC2086 # CLAUDE_ARGS is deliberately word-split.
exec claude ${CLAUDE_ARGS:-} "$PROMPT"
